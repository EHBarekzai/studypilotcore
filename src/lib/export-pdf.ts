/**
 * Lightweight PDF export: renders a printable report in a new window and calls
 * the browser's print dialog (choose "Save as PDF"). No extra dependencies.
 */

export type ReportTable = { heading: string; columns: string[]; rows: (string | number)[][] };
export type ReportStat = { label: string; value: string };

export type ReportDocument = {
  title: string;
  subtitle?: string;
  stats?: ReportStat[];
  sections?: { heading: string; lines: string[] }[];
  tables?: ReportTable[];
};

function escapeHtml(value: string | number) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function buildHtml(doc: ReportDocument) {
  const generated = new Date().toLocaleString();
  const stats = (doc.stats ?? [])
    .map(
      (s) =>
        `<div class="stat"><span class="label">${escapeHtml(s.label)}</span><strong>${escapeHtml(s.value)}</strong></div>`,
    )
    .join("");

  const sections = (doc.sections ?? [])
    .map(
      (section) =>
        `<section><h2>${escapeHtml(section.heading)}</h2><ul>${section.lines
          .map((line) => `<li>${escapeHtml(line)}</li>`)
          .join("")}</ul></section>`,
    )
    .join("");

  const tables = (doc.tables ?? [])
    .map(
      (table) => `<section><h2>${escapeHtml(table.heading)}</h2><table>
        <thead><tr>${table.columns.map((c) => `<th>${escapeHtml(c)}</th>`).join("")}</tr></thead>
        <tbody>${table.rows
          .map((row) => `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join("")}</tr>`)
          .join("")}</tbody>
      </table></section>`,
    )
    .join("");

  return `<!doctype html><html lang="en"><head><meta charset="utf-8" />
  <title>${escapeHtml(doc.title)}</title>
  <style>
    :root { color-scheme: light; }
    * { box-sizing: border-box; }
    body { font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif; margin: 32px; color: #101828; }
    header { border-bottom: 2px solid #0f766e; padding-bottom: 12px; margin-bottom: 20px; }
    h1 { font-size: 22px; margin: 0 0 4px; }
    .muted { color: #667085; font-size: 12px; margin: 0; }
    .stats { display: flex; flex-wrap: wrap; gap: 10px; margin-bottom: 22px; }
    .stat { border: 1px solid #e4e7ec; border-radius: 10px; padding: 10px 14px; min-width: 132px; }
    .stat .label { display: block; font-size: 10px; text-transform: uppercase; letter-spacing: .06em; color: #667085; }
    .stat strong { font-size: 17px; }
    section { margin-bottom: 22px; page-break-inside: avoid; }
    h2 { font-size: 14px; text-transform: uppercase; letter-spacing: .06em; color: #0f766e; margin: 0 0 8px; }
    ul { margin: 0; padding-left: 18px; font-size: 12.5px; line-height: 1.6; }
    table { width: 100%; border-collapse: collapse; font-size: 12px; }
    th, td { border: 1px solid #e4e7ec; padding: 6px 8px; text-align: left; }
    th { background: #f2f4f7; font-size: 10.5px; text-transform: uppercase; letter-spacing: .04em; }
    footer { margin-top: 24px; font-size: 10.5px; color: #98a2b3; }
    @page { margin: 16mm; }
  </style></head><body>
  <header>
    <h1>${escapeHtml(doc.title)}</h1>
    ${doc.subtitle ? `<p class="muted">${escapeHtml(doc.subtitle)}</p>` : ""}
    <p class="muted">StudyPilot · generated ${escapeHtml(generated)}</p>
  </header>
  ${stats ? `<div class="stats">${stats}</div>` : ""}
  ${sections}
  ${tables}
  <footer>Generated by StudyPilot.</footer>
  </body></html>`;
}

/** Opens the print dialog for a report. Returns false if a popup was blocked. */
export function exportReportToPdf(doc: ReportDocument) {
  const win = window.open("", "_blank", "width=900,height=1000");
  if (!win) return false;
  win.document.write(buildHtml(doc));
  win.document.close();
  win.focus();
  // Give the new document a tick to lay out before printing.
  window.setTimeout(() => win.print(), 350);
  return true;
}
